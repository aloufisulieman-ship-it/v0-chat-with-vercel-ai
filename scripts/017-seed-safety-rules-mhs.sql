WITH target_org AS (
  SELECT DISTINCT o.id AS org_id, o.name AS org_name
    FROM organization o
    LEFT JOIN company c ON c."organizationId" = o.id
   WHERE o.name ILIKE '%الأيادي الفضية الحديثة%'
      OR c.name ILIKE '%الأيادي الفضية الحديثة%'
),
target_user AS (
  SELECT u.id AS user_id, u.name AS user_name, u.email AS user_email, u."createdAt" AS user_created_at
    FROM "user" u, target_org t
   WHERE u."organizationId" = t.org_id
     AND u.role = 'admin'
   ORDER BY u."createdAt" ASC
   LIMIT 1
),
seed_locations (location) AS (
  VALUES
    ('الساحة — التحميل والتفريغ (العمال)'),
    ('الساحة — مسارات الرافعات الشوكية'),
    ('الساحة — مواقف الشاحنات (الزوار)'),
    ('الورشة — منطقة الإصلاح'),
    ('الورشة — منطقة الشحن الكهربائي (الرافعات والتوكتوك)'),
    ('الورشة — فنيو الورشة'),
    ('مخزن قطع الغيار ومكتب الورشة'),
    ('مكتب السلامة والعمليات ومكاتب الإدارة التنفيذية (مبنى الورشة)'),
    ('المكتب الرئيسي')
)
SELECT
  (SELECT count(*) FROM target_org)                                            AS matching_orgs_count,
  (SELECT org_id FROM target_org LIMIT 1)                                      AS org_id,
  (SELECT org_name FROM target_org LIMIT 1)                                    AS org_name,
  (SELECT user_id FROM target_user)                                            AS owner_user_id,
  (SELECT user_name FROM target_user)                                          AS owner_user_name,
  (SELECT user_email FROM target_user)                                         AS owner_user_email,
  (SELECT count(*) FROM "user" u, target_org t
    WHERE u."organizationId" = t.org_id AND u.role = 'admin')                  AS admin_accounts_in_org,
  (SELECT count(*) FROM safety_rules sr, target_org t
    WHERE sr."organizationId" = t.org_id
      AND sr.location IN (SELECT location FROM seed_locations))               AS existing_rows_to_be_replaced;

