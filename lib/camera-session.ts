// معرّف جلسة الكاميرا: مشتقّ من (حساب الجهاز + اسم المفتش المُدخل يدوياً).
//
// السبب: عدّة مفتشين قد يستخدمون نفس الرابط/الجهاز بلا حساب منفصل، لذا لا يمكن
// الاعتماد على معرّف الحساب وحده لتمييزهم. باشتقاق المعرّف من اسم المفتش المُدخل:
//   - كل مفتش (بنفس الاسم) يحصل على جلسة/سجل كاميرا خاص به.
//   - إعادة المفتش نفسه لفتح البث لاحقاً تُحدّث السجل نفسه (onConflictDoUpdate)
//     بدل إنشاء كاميرا جديدة في كل مرة.
// دمج معرّف الحساب في المدخل يمنع تصادم المعرّف بين حسابين مختلفين لهما اسم مفتش مطابق.
//
// دالة تجزئة نقية (djb2) بلا اعتماد على مكتبات؛ المعرّف غير أمني (مجرد مفتاح ثابت
// وآمن للاستخدام في المسارات وروابط Blob)، لذا لا حاجة لتجزئة تشفيرية.
export function sessionCameraId(userId: string, inspectorName: string): string {
  const normalized = (inspectorName || "")
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ")
  const input = `${userId}::${normalized}`
  let h = 5381
  for (let i = 0; i < input.length; i++) {
    h = ((h << 5) + h + input.charCodeAt(i)) >>> 0
  }
  return `cam-${h.toString(16).padStart(8, "0")}`
}
